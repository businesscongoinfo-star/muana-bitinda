const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('code.gs', 'utf8');
let locked = false, releases = 0;
const ctx = vm.createContext({console, LockService: {getScriptLock: () => ({waitLock() { assert.equal(locked, false); locked = true; }, releaseLock() { locked = false; releases++; }})}});
vm.runInContext(source, ctx);
let appended;
ctx.appendSafeRow_({appendRow: row => {appended = row;}}, ['001', '+242', '=1+1', 0, '']);
assert.deepEqual(Array.from(appended), ["'001", "'+242", "'=1+1", 0, '']);
const removed = [];
ctx.CacheService = {getScriptCache: () => ({get: () => JSON.stringify({id:'u1',role:'PARTENAIRE',partnerCode:'P1'}),remove: x => removed.push(x)})};
ctx.getRows_ = () => [['u1','Name','e','', '', 'PARTENAIRE','P1','ACTIF']];
assert.equal(ctx.getSession_('token').id, 'u1');
ctx.getRows_ = () => [['u1','Name','e','', '', 'PARTENAIRE','P1','SUSPENDU']];
assert.throws(() => ctx.getSession_('token'), /désactivé/);
assert.deepEqual(removed, ['SESSION_token']);
ctx.getSession_ = () => ({role:'PARTENAIRE', partnerCode:'P1', name:'N'});
ctx.calculateStock_ = () => 5;
ctx.generateId_ = () => 'id';
let rows = [], movements = [];
ctx.getSheet_ = () => ({appendRow: row => rows.push(row)});
ctx.addMovement_ = m => movements.push(m);
ctx.addDelivery('t', {productCode:'P', quantity:7, status:'ANNULÉE'});
assert.equal(rows.length, 1); assert.equal(movements.length, 0);
assert.throws(() => ctx.addDelivery('t', {productCode:'P', quantity:7}), /Stock insuffisant/);
assert.throws(() => ctx.addDelivery('t', {productCode:'P', quantity:'nope'}), /quantité/);
ctx.addDelivery('t', {productCode:'P', quantity:2, status:'EN ATTENTE'});
assert.equal(movements.length, 1); assert.equal(movements[0].exit, 2);
assert.equal(releases, 4); assert.equal(locked, false);
const html = fs.readFileSync('index.html', 'utf8');
new vm.Script(html.match(/<script>([\s\S]*?)<\/script>/)[1]);
assert.match(html, /stockData = data\.products \|\| \[\]/);
assert.match(html, /getElementById\('adminStatsContainer'\)\.innerHTML/);
console.log('OK : syntaxe, protection des textes, suspension, stock, annulation, verrou et branchements interface.');
